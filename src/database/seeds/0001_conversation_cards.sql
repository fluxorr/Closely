LOCK TABLE closely_questions IN SHARE ROW EXCLUSIVE MODE;

WITH inserted AS (
  INSERT INTO closely_questions (id, kind, category, text, answer_reveal, public_preview)
  SELECT md5('closely-conversation-import-1:' || item.category || ':' || item.text)::uuid,
    'card',
    item.category,
    item.text,
    item.category IN ('deep', 'fun', 'memory'),
    item.category = 'fun'
      AND item.text = $q$What would be the headline if our most ridiculous argument made the local news?$q$
      AND NOT EXISTS (SELECT 1 FROM closely_questions WHERE enabled AND public_preview)
  FROM conversation_card_import AS item
  WHERE NOT EXISTS (
    SELECT 1 FROM closely_questions AS existing
    WHERE existing.kind = 'card'
      AND existing.category = item.category
      AND lower(btrim(existing.text)) = lower(btrim(item.text))
  )
  ON CONFLICT (id) DO NOTHING
  RETURNING category
)
SELECT category, count(*)::int AS inserted
FROM inserted
GROUP BY category
ORDER BY category;

